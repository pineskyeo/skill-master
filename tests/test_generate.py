class TestTargetsData(unittest.TestCase):
    def target(self, tool):
        with open(os.path.join(ROOT, "targets", tool + ".json"), encoding="utf-8") as f:
            return json.load(f)

    def schema(self, name):
        with open(os.path.join(ROOT, "schemas", name), encoding="utf-8") as f:
            return json.load(f)

    def test_each_closed_wrapper_schema_holds_exactly_the_target_keys(self):
        for tool in ("claude", "codex", "opencode"):
            with self.subTest(tool):
                w = self.target(tool)["wrapper"]
                fields = list(w["required"]) + list(w["fields"])
                props = self.schema("wrapper-%s.schema.json" % tool)["properties"]
                names = set()
                for k, sub in props.items():
                    if any(f.startswith(k + ".") for f in fields):
                        names |= {k + "." + kk for kk in sub["properties"]}
                    else:
                        names.add(k)
                self.assertEqual(names, set(fields))
        self.assertEqual(set(self.schema("wrapper-hermes.schema.json")["properties"]),
                         {"header", "title", "description", "body"})

    def test_every_schema_object_is_closed(self):
        def walk(node, where):
            if isinstance(node, dict):
                if node.get("type") == "object" or "properties" in node:
                    self.assertIn("additionalProperties", node, where)
                    self.assertNotEqual(node["additionalProperties"], True, where)
                for k, v in node.items():
                    walk(v, where + "/" + k)
            elif isinstance(node, list):
                for i, v in enumerate(node):
                    walk(v, "%s/%d" % (where, i))
        for name in ("wrapper-claude", "wrapper-codex", "wrapper-opencode", "wrapper-hermes", "codex-openai-yaml"):
            with self.subTest(name):
                doc = self.schema(name + ".schema.json")
                S.compile_schema(doc)
                walk(doc, name)

    def test_the_claude_tool_names_map_back_to_exactly_their_class(self):
        names = self.target("claude")["render"]["tool_names"]
        self.assertEqual(list(names), list(VOCAB))
        for c in VOCAB:
            self.assertEqual(PR.capabilities(names[c]), ({c}, []), c)
            self.assertEqual(", ".join(names[c]), P.CLAUDE_TOOL_NAMES[c], c)

    def test_the_three_bodies_render_the_same_text_and_hermes_adds_its_title(self):
        bodies = {t: self.target(t)["render"]["body"] for t in ("claude", "codex", "opencode", "hermes")}
        self.assertEqual(bodies["claude"], "You are {name}.\n\nGoal: {goal}\n\n{body}")
        self.assertEqual(bodies["codex"], bodies["claude"])
        self.assertEqual(bodies["opencode"], bodies["claude"])
        self.assertEqual(bodies["hermes"], "# {name}\n\n{description}\n\n" + bodies["claude"])

