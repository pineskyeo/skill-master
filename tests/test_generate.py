class TestReader(unittest.TestCase):
    def fm(self, block, top="permission:"):
        return "---\ndescription: x\n%s\n%s---\nbody\n" % (top, block)

    def ok(self, block):
        meta, body, err = loaders.parse_frontmatter_maps(self.fm(block), ["permission"])
        self.assertIsNone(err, err)
        self.assertEqual(body, "body")
        return meta["permission"]

    def bad(self, text, fragment):
        meta, _, err = loaders.parse_frontmatter_maps(text, ["permission"])
        self.assertIsNone(meta, text)
        self.assertIn(fragment, err, text)
        self.assertRegex(err, r"^frontmatter line \d+: ")

    def test_the_wildcard_and_the_pattern_map_are_read_in_order(self):
        perm = self.ok('  "*": deny\n  read: allow\n  bash:\n    "*": allow\n    "git push*": deny\n  lsp: "allow"\n')
        self.assertEqual(perm, {"*": "deny", "read": "allow", "bash": {"*": "allow", "git push*": "deny"}, "lsp": "allow"})
        self.assertEqual(list(perm), ["*", "read", "bash", "lsp"])
        self.assertEqual(list(perm["bash"]), ["*", "git push*"])

    def test_a_second_block_refuses(self):
        self.bad(self.fm('  read: allow\npermission:\n  edit: deny\n'), "duplicate key 'permission'")

    def test_a_key_repeated_after_decoding_refuses_at_both_levels(self):
        for block in ('  "*": deny\n  "\\x2a": allow\n', '  read: allow\n  "read": deny\n',
                      '  bash:\n    "*": allow\n    "\\x2a": deny\n', '  "\\u002a": deny\n  "*": allow\n'):
            with self.subTest(block):
                self.bad(self.fm(block), "duplicate key")

    def test_other_indentation_refuses(self):
        for block in ('   read: allow\n', '      read: allow\n', '    read: allow\n', '  bash:\n      "*": allow\n',
                      '  bash:\n   "*": allow\n'):
            with self.subTest(block):
                self.bad(self.fm(block), "indentation")

    def test_a_scalar_followed_by_deeper_lines_refuses(self):
        self.bad(self.fm('  bash: deny\n    "*": allow\n'), "scalar")

