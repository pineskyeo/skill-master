class TestCapabilityMapping(Base):
    def files(self, caps):
        d = self.generated("cap-agent", agent_md("cap-agent", ", ".join(caps)), parent="caps-" + "-".join(caps))
        claude = loaders.parse_frontmatter_ex(self.text(d, "wrappers/claude/cap-agent.md"))[0]
        codex = loaders.parse_toml(self.text(d, "wrappers/codex/cap-agent.toml"))
        opencode = loaders.parse_frontmatter_maps(self.text(d, "wrappers/opencode/cap-agent.md"), ["permission"])[0]
        return d, claude, codex, opencode

    def assert_mapping(self, caps):
        d, claude, codex, opencode = self.files(caps)
        self.assertEqual(claude["tools"], ", ".join(CLAUDE_NAMES[c] for c in VOCAB if c in caps), caps)
        self.assertIs(codex["features"]["shell_tool"], "shell" in caps, caps)
        perm = opencode["permission"]
        self.assertEqual(list(perm)[0], "*", caps)
        self.assertEqual(perm["*"], "deny", caps)
        self.assertEqual(set(perm), {"*"} | set(OC_KEYS), caps)
        grant = {k: perm[k]["*"] if isinstance(perm[k], dict) else perm[k] for k in OC_KEYS}
        self.assertEqual({k for k, v in grant.items() if v == "allow"}, set().union(*(OPENCODE_ALLOW[c] for c in caps)))
        values = [v for v in perm.values() if isinstance(v, str)] + [x for v in perm.values() if isinstance(v, dict)
                                                                     for x in v.values()]
        self.assertTrue(set(values) <= {"allow", "deny"}, caps)
        self.assertEqual(perm["external_directory"], "deny", caps)
        if "shell" in caps:
            self.assertEqual(list(perm["bash"]), ["*"] + PATTERNS)
            self.assertEqual(perm["bash"]["*"], "allow")
            self.assertEqual({perm["bash"][p] for p in PATTERNS}, {"deny"})
        else:
            self.assertEqual(perm["bash"], "deny", caps)
        self.assertEqual(os.listdir(os.path.join(d, "wrappers", "hermes")), ["SOUL.md"])
        soul = self.text(d, "wrappers/hermes/SOUL.md")
        for word in ("permission", "allow", "deny", "tools"):
            self.assertNotIn(word, soul, caps)

    def test_each_capability_alone_on_every_tool(self):
        for c in VOCAB:
            with self.subTest(c):
                self.assert_mapping([c])

    def test_all_eight_capabilities_together(self):
        self.assert_mapping(list(VOCAB))

    def test_a_search_only_agent_gets_no_read_tool(self):
        _, claude, _, opencode = self.files(["search"])
        self.assertEqual(claude["tools"], "Glob, Grep")
        self.assertEqual(opencode["permission"]["read"], "deny")


