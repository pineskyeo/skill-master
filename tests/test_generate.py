class TestParityWildcard(Base):
    def variant(self, edit, md=None, name="scout-reader"):
        d = self.generated(name, md, parent="v%d" % len(os.listdir(self.tmp)))
        rel = "wrappers/opencode/%s.md" % name
        self.put(d, rel, edit(self.text(d, rel)))
        r = eva.check(d)
        return row(r, "parity-wrapper-opencode"), row(r, "parity-permissions-opencode")

    def test_the_generated_wildcard_first_passes_the_wrapper_and_stays_review(self):
        w, p = self.variant(lambda t: t)
        self.assertEqual((w["status"], p["status"]), ("pass", "needs-review"))

    def test_a_wildcard_that_is_not_first_fails(self):
        def move(t):
            return t.replace('  "*": "deny"\n', "").replace('  skill: "deny"\n', '  skill: "deny"\n  "*": "deny"\n')
        w, p = self.variant(move)
        self.assertEqual(w["status"], "fail")
        self.assertIn("the wildcard key '*' must be the first key", w["reason"])
        self.assertNotEqual(p["status"], "pass")

    def test_a_wildcard_that_allows_fails(self):
        w, _ = self.variant(lambda t: t.replace('"*": "deny"', '"*": "allow"', 1))
        self.assertEqual(w["status"], "fail")
        self.assertIn("the wildcard key '*' must be deny", w["reason"])

    def test_a_map_on_a_key_other_than_bash_fails(self):
        w, _ = self.variant(lambda t: t.replace('  edit: "deny"\n', '  edit:\n    "*": "deny"\n'))
        self.assertEqual(w["status"], "fail")
        self.assertIn("permission.edit: a pattern map is allowed only for bash", w["reason"])

    def test_a_bash_map_must_start_with_the_wildcard(self):
        w, _ = self.variant(lambda t: t.replace('  bash: "deny"\n', '  bash:\n    "git push*": "deny"\n    "*": "allow"\n'))
        self.assertEqual(w["status"], "fail")
        self.assertIn("permission.bash: a pattern map must start with '*'", w["reason"])

    def test_a_bash_pattern_entry_that_allows_fails(self):
        w, _ = self.variant(lambda t: t.replace('  bash: "deny"\n', '  bash:\n    "*": "deny"\n    "python3 *": "allow"\n'))
        self.assertEqual(w["status"], "fail")
        self.assertIn("permission.bash: pattern 'python3 *' must be deny", w["reason"])

    def test_the_wildcard_is_accepted_not_required(self):
        w, p = self.variant(lambda t: t.replace('  "*": "deny"\n', ""))
        self.assertEqual((w["status"], p["status"]), ("pass", "needs-review"))

    def test_the_bash_map_grant_is_its_wildcard_value(self):
        w, p = self.variant(lambda t: t, shell_md(), "shell-runner")
        self.assertEqual((w["status"], p["status"]), ("pass", "needs-review"))
        self.assertIn("['read', 'search', 'shell']", p["reason"])
        w, p = self.variant(lambda t: t.replace('    "*": "allow"\n', '    "*": "deny"\n'), shell_md(), "shell-runner")
        self.assertEqual((w["status"], p["status"]), ("pass", "fail"))
        self.assertIn("wrapper grants ['read', 'search'], AGENT.md capabilities need ['read', 'search', 'shell']",
                      p["reason"])

    def test_a_duplicate_wildcard_makes_the_wrapper_unusable(self):
        w, p = self.variant(lambda t: t.replace('  "*": "deny"\n', '  "*": "deny"\n  "*": "allow"\n'))
        self.assertEqual(w["status"], "fail")
        self.assertIn("duplicate key", w["reason"])
        self.assertEqual(p["status"], "n/a")


