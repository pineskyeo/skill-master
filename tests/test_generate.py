def sha_file(p):
    with open(p, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def snapshot(top):
    """Every entry under top, links not followed: (rel, kind, size, sha256, mode) for files, the target for links."""
    out = []
    for dp, dn, fn in os.walk(top):
        dn.sort()
        for n in sorted(dn + fn):
            p = os.path.join(dp, n)
            st = os.lstat(p)
            rel = os.path.relpath(p, top)
            if stat.S_ISLNK(st.st_mode):
                out.append((rel, "link", os.readlink(p)))
            elif stat.S_ISREG(st.st_mode):
                out.append((rel, "file", st.st_size, sha_file(p), stat.S_IMODE(st.st_mode)))
            else:
                out.append((rel, "dir"))
    return out


def row(r, cid):
    rows = [c for c in r.checks if c["id"] == cid]
    if len(rows) != 1:
        raise AssertionError("%d rows for %s" % (len(rows), cid))
    return rows[0]


def run_main(argv):
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        try:
            rc = eva.main(argv)
        except SystemExit as e:
            rc = ("SystemExit", e.code)
    return rc, out.getvalue(), err.getvalue()


class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp)

    def put(self, path, rel, data):
        fp = os.path.join(path, *rel.split("/"))
        os.makedirs(os.path.dirname(fp), exist_ok=True)
        with open(fp, "wb") as f:
            f.write(data.encode("utf-8") if isinstance(data, str) else data)

    def get(self, path, rel):
        with open(os.path.join(path, *rel.split("/")), "rb") as f:
            return f.read()

    def text(self, path, rel):
        return self.get(path, rel).decode("utf-8")

    def unit(self, name="scout-reader", md=None, folder=None, parent="units"):
        d = os.path.join(self.tmp, parent, folder or name)
        self.put(d, "AGENT.md", agent_md(name) if md is None else md)
        return d

    def skill(self, name="quiet-skill", extra="", raw=None, files=None, parent="skills"):
        d = os.path.join(self.tmp, parent, name)
        self.put(d, "SKILL.md", skill_md(name, extra) if raw is None else raw)
        for rel, data in (files or {}).items():
            self.put(d, rel, data)
        return d

    def gen(self, path, check=False):
        return run_main(["generate"] + (["--check"] if check else []) + [path])

    def generated(self, name="scout-reader", md=None, **kw):
        d = self.unit(name, md, **kw)
        rc, out, err = self.gen(d)
        self.assertEqual(rc, 0, (out, err))
        return d

    def assert_check(self, d, rc_want, *names):
        rc, out, err = self.gen(d, check=True)
        self.assertEqual(rc, rc_want, (out, err))
        for n in names:
            self.assertIn(n, out + err)
        return out + err

    def assert_refused(self, d, fragments, top=None, check_too=True):
        top = top or self.tmp
        before = snapshot(top)
        rc, out, err = self.gen(d)
        self.assertEqual(rc, 2, (out, err))
        for f in fragments:
            self.assertIn(f, err)
        self.assertEqual(snapshot(top), before)
        return err


