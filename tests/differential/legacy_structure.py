def _verb_forms(v):
    f = {v, v + "s", v + "es", v + "ing"}
    if v.endswith("e"): f.add(v[:-1] + "ing")
    if v.endswith("y"): f.add(v[:-1] + "ies")
    if re.search(r"[^aeiou][aeiou][bdgmnprt]$", v): f.add(v + v[-1] + "ing")  # split -> splitting
    return f

TASK_VERB_FORMS = {f: v for v in TASK_VERBS for f in _verb_forms(v)}

